export const uid = () => `${Date.now()}-${Math.random().toString(36).slice(2, 7)}`;

export const element = (type, values) => ({
  id: uid(),
  type,
  x: 20,
  y: 20,
  width: 120,
  height: 32,
  rotation: 0,
  opacity: 1,
  ...values,
});

/* ---------- compact builders ---------- */
const T = (text, x, y, w, h, fontSize, color, bold = false, extra = {}) =>
  element("text", { text, x, y, width: w, height: h, fontSize, color, bold, ...extra });

const PH = (x, y, w, h, extra = {}) =>
  element("photo", { x, y, width: w, height: h, ...extra });

const SH = (shape, x, y, w, h, bg, extra = {}) =>
  element("shape", {
    shape,
    x,
    y,
    width: w,
    height: h,
    bg,
    text: "",
    fillMode: "solid",
    radius: shape === "circle" ? 50 : shape === "pill" ? 999 : 0,
    ...extra,
  });

const QR = (x, y, size) => element("qr", { x, y, width: size, height: size });
const BC = (x, y, w, h = 26) => element("barcode", { x, y, width: w, height: h });

